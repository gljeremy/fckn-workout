import type { DayKind, Focus, Gear, Goal, Level, Pattern, Role, Setup, Slot, TemplateDay } from './types';

export interface Template {
  id: string;
  name: string;
  tagline: string;
  split: string;
  days: number;
  /** How well it serves each goal, 0–1. */
  goals: Record<Goal, number>;
  levels: Record<Level, number>;
  /** How well it suits each equipment setup, 0–1; 0 rules it out. */
  setups: Record<Setup, number>;
  /** Gear it can't do without. */
  requires?: Gear[];
  nativeSetup?: Setup;
  /** Muscles it gives extra work to. */
  emphasis?: Focus[];
  /** Session length it's written for, in minutes. */
  minutes: [number, number];
  /** Progression in a sentence, for the details panel. */
  progression: string;
  week: TemplateDay[];
}

